// 3. Close Case Study Modal
export function closeCaseStudy() {
  const modal = document.getElementById('case-study-modal');
  if (modal) {
    modal.classList.add('hidden');
    document.body.style.overflow = 'auto';
  }
}

// 4. Inquire from Case Study
export function inquireFromCaseStudy(categoryKey) {
  closeCaseStudy();
  const select = document.getElementById('project-type');
  if (select) {
    if (categoryKey === 'social') select.value = 'social-media';
    else if (categoryKey === 'branding') select.value = 'branding';
    else if (categoryKey === 'posters') select.value = 'posters';
    else if (categoryKey === 'campaigns') select.value = 'campaign';
    else select.value = 'other';
  }
  const contact = document.getElementById('contact');
  if (contact) {
    contact.scrollIntoView({ behavior: 'smooth' });
  }
}

// 5. Copy HEX code with tooltip
export function copyHex(hex, buttonEl) {
  navigator.clipboard.writeText(hex).then(() => {
    const tooltip = document.createElement('span');
    tooltip.className = 'absolute -top-7 left-1/2 -translate-x-1/2 px-2 py-0.5 rounded bg-[#350d1c] text-white text-[10px] font-bold whitespace-nowrap shadow-md';
    tooltip.innerText = 'Copied!';
    buttonEl.appendChild(tooltip);
    setTimeout(() => tooltip.remove(), 1800);
  });
}

