// 10. Kathmandu Time Clock (UTC+5:45)
function initNepalTimeClock() {
  const clockEl = document.getElementById('nepal-time-clock');
  if (!clockEl) return;

  function update() {
    const now = new Date();
    const utcTime = now.getTime() + now.getTimezoneOffset() * 60000;
    const nepalOffset = 5.75 * 3600000;
    const nepalDate = new Date(utcTime + nepalOffset);

    const hours = nepalDate.getHours().toString().padStart(2, '0');
    const minutes = nepalDate.getMinutes().toString().padStart(2, '0');
    const ampm = nepalDate.getHours() >= 12 ? 'PM' : 'AM';

    clockEl.innerText = `${hours}:${minutes} ${ampm} NPT`;
  }

  update();
  setInterval(update, 10000);
}

// 11. Interactive Category Filter & Search Logic
function initFilterAndSearch() {
  const filterTabs = document.querySelectorAll('.filter-tab');
  const projectItems = document.querySelectorAll('.project-item');
  const countEl = document.getElementById('project-count');
  const searchInput = document.getElementById('project-search');

  let currentFilter = 'all';
  let currentSearch = '';

  function applyFilters() {
    let visibleCount = 0;

    projectItems.forEach(item => {
      const category = item.getAttribute('data-category');
      const title = (item.getAttribute('data-title') || '').toLowerCase();
      const text = item.innerText.toLowerCase();

      const matchesCat = currentFilter === 'all' || category === currentFilter;
      const matchesSearch = currentSearch === '' || title.includes(currentSearch) || text.includes(currentSearch);

      if (matchesCat && matchesSearch) {
        item.style.display = 'flex';
        visibleCount++;
      } else {
        item.style.display = 'none';
      }
    });

    if (countEl) {
      countEl.innerText = visibleCount;
    }
  }

  filterTabs.forEach(tab => {
    tab.addEventListener('click', () => {
      filterTabs.forEach(t => {
        t.classList.remove('bg-[#8a4b5c]', 'text-white', 'shadow-sm', 'active-filter');
        t.classList.add('text-[#524346]');
      });
      tab.classList.add('bg-[#8a4b5c]', 'text-white', 'shadow-sm', 'active-filter');
      tab.classList.remove('text-[#524346]');

      currentFilter = tab.getAttribute('data-filter') || 'all';
      applyFilters();
    });
  });

  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      currentSearch = (e.target.value || '').trim().toLowerCase();
      applyFilters();
    });
  }
}

